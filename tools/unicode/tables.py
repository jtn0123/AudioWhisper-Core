"""Writes crates/apple-text/src/tables/*.rs from the dumps of icu.c and swift.swift."""

import sys
from pathlib import Path

icu_dump, swift_dump, out = sys.argv[1], sys.argv[2], Path(sys.argv[3])

categories = {}
simple = {}
full = {}
closures = {}
version = None
for line in Path(icu_dump).read_text().splitlines():
    kind, *fields = line.split(" ")
    if kind == "version":
        version = fields[0]
    elif kind == "gc":
        categories[int(fields[0], 16)] = int(fields[1])
    elif kind == "simple":
        simple[int(fields[0], 16)] = int(fields[1], 16)
    elif kind == "full":
        units = [int(it, 16) for it in fields[1:]]
        full[int(fields[0], 16)] = "".join(map(chr, units)).encode("utf-16", "surrogatepass").decode("utf-16")
    elif kind == "closure":
        closures[fields[0]] = [int(it, 16) for it in fields[1:]]

swift = {}
for line in Path(swift_dump).read_text().splitlines():
    name, *spans = line.split(" ")
    swift[name] = [tuple(int(it, 16) for it in span.split("-")) for span in spans if span]

# A full folding of one scalar is the simple one; only the expansions need their own table.
expansions = {}
for scalar, folded in full.items():
    if len(folded) == 1:
        assert simple.get(scalar) == ord(folded), f"{scalar:X} folds differently"
    else:
        assert len(folded) <= 3
        expansions[scalar] = folded
for scalar in simple:
    assert scalar in full, f"{scalar:X} has a simple folding only"
assert closures["word"] == closures["filler"]


def spans(test):
    result, start = [], None
    for value in range(0x110001):
        hit = value <= 0x10FFFF and test(value)
        if hit and start is None:
            start = value
        if not hit and start is not None:
            result.append((start, value - 1))
            start = None
    return result


def flat(pairs):
    return ", ".join(f"0x{a:X}, 0x{b:X}" for a, b in pairs)


def ranges(name, doc, pairs):
    return f"/// {doc}\npub const {name}: &[u32] = &[{flat(pairs)}];\n"


HEADER = """//! Generated by tools/unicode-tables.sh from {source}; don't edit. Ranges are flat
//! `[first, last, first, last, ...]` lists of scalar values.

"""

gc = lambda *wanted: (lambda value: categories.get(value) in wanted)
(out / "icu.rs").write_text(
    HEADER.format(source=f"macOS's ICU (Unicode {version})")
    + ranges("LETTER", "General category L.", spans(gc(1, 2, 3, 4, 5)))
    + ranges("NUMBER", "General category N.", spans(gc(9, 10, 11)))
    + ranges("UPPERCASE_LETTER", "General category Lu.", spans(gc(1)))
    + ranges("LOWERCASE_LETTER", "General category Ll.", spans(gc(2)))
    + ranges("TITLECASE_LETTER", "General category Lt.", spans(gc(3)))
    + "/// What case-insensitive matching adds to `[\\p{L}\\p{N}_]`.\n"
    + f"pub const WORD_CASE_CLOSURE: &[u32] = &[{', '.join(f'0x{it:X}' for it in closures['word'])}];\n"
)

simple_pairs = ", ".join(f"0x{a:X}, 0x{b:X}" for a, b in sorted(simple.items()))
expansion_rows = ", ".join(
    f"0x{a:X}, " + ", ".join(f"0x{ord(c):X}" for c in (b + "\0\0")[:3]) for a, b in sorted(expansions.items())
)
(out / "folding.rs").write_text(
    HEADER.format(source=f"macOS's ICU (Unicode {version})")
    + "/// Simple case folding: `[scalar, folded, scalar, folded, ...]`, for every scalar that changes.\n"
    + f"pub const SIMPLE: &[u32] = &[{simple_pairs}];\n\n"
    + "/// Full case folding where it is more than one scalar: `[scalar, a, b, c, ...]`, 0 padded.\n"
    + f"pub const EXPANSIONS: &[u32] = &[{expansion_rows}];\n"
)

(out / "swift.rs").write_text(
    HEADER.format(source="the Swift runtime and Foundation")
    + ranges("NUMERIC", "`Unicode.Scalar.Properties.numericType != nil`.", swift["numeric"])
    + ranges("ALPHABETIC", "`Unicode.Scalar.Properties.isAlphabetic`.", swift["alphabetic"])
    + ranges("WHITESPACES", "`CharacterSet.whitespaces`.", swift["whitespaces"])
    + ranges("NEWLINES", "`CharacterSet.newlines`.", swift["newlines"])
    + ranges(
        "EXTEND",
        "The scalars Foundation's non-literal search won't end a match before.",
        swift["extend"],
    )
)
